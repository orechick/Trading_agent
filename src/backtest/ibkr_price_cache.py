def load_weekly_prices() -> pd.DataFrame:
    """Load all 15 ETF weekly close prices into a DataFrame."""
    idx = pd.to_datetime(_DATES)

    data = {
        "SPY": _SPY, "BND": _BND, "GLD": _GLD, "TLT": _TLT, "VT": _VT,
        "XLF": _XLF, "XLV": _XLV, "EFA": _EFA, "EEM": _EEM, "IWM": _IWM,
        "VNQ": _VNQ, "TIP": _TIP, "DBC": _DBC,
    }

    df = pd.DataFrame(data, index=idx)

    # XLK and XLE have 261 points (missing first date) — align with NaN prefix
    for ticker, arr in [("XLK", _XLK), ("XLE", _XLE)]:
        s = pd.Series([np.nan] + list(arr) if len(arr) < len(idx) else list(arr),
                      index=idx[:len(arr) + (1 if len(arr) < len(idx) else 0)])
        df[ticker] = s

    return df
